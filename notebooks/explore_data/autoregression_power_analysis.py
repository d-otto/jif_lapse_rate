def save_analysis_results(ar_results, psd_results, output_dir):
    """Save analysis results to CSV files"""
    
    print("\nSaving analysis results...")
    
    # Prepare autoregression results
    ar_data = []
    for site_name, heights in ar_results.items():
        for height, sensors in heights.items():
            for sensor_result in sensors:
                ar_data.append({
                    'sensor_key': sensor_result['sensor_key'],
                    'site_name': site_name,
                    'sensor_height': height,
                    'optimal_order_aic': sensor_result['optimal_order_aic'],
                    'optimal_order_bic': sensor_result['optimal_order_bic'],
                    'ar1_coefficient': sensor_result['ar1_coefficient'],
                    'lag1_autocorr': sensor_result['lag1_autocorr'],
                    'e_folding_time': sensor_result['e_folding_time'],
                    'half_life_time': sensor_result['half_life_time'],
                    'high_freq_variance': sensor_result['high_freq_variance'],
                    'ljung_box_pvalue': sensor_result['ljung_box_pvalue'],
                    'r_squared': sensor_result['r_squared'],
                    'aic': sensor_result['aic'],
                    'bic': sensor_result['bic'],
                    'n_obs': sensor_result['n_obs']
                })
    
    ar_df = pd.DataFrame(ar_data)
    ar_df.to_csv(output_dir / "autoregression_results.csv", index=False)
    
    # Prepare power spectral density results
    psd_data = []
    for site_name, heights in psd_results.items():
        for height, sensors in heights.items():
            for sensor_result in sensors:
                psd_data.append({
                    'sensor_key': sensor_result['sensor_key'],
                    'site_name': site_name,
                    'sensor_height': height,
                    'total_power': sensor_result['total_power'],
                    'very_highfreq_power': sensor_result['very_highfreq_power'],
                    'highfreq_power': sensor_result['highfreq_power'],
                    'medfreq_power': sensor_result['medfreq_power'],
                    'lowfreq_power': sensor_result['lowfreq_power'],
                    'very_highfreq_fraction': sensor_result['very_highfreq_fraction'],
                    'highfreq_fraction': sensor_result['highfreq_fraction'],
                    'medfreq_fraction': sensor_result['medfreq_fraction'],
                    'lowfreq_fraction': sensor_result['lowfreq_fraction'],
                    'nperseg': sensor_result['nperseg'],
                    'noverlap': sensor_result['noverlap'],
                    'n_obs': sensor_result['n_obs']
                })
    
    psd_df = pd.DataFrame(psd_data)
    psd_df.to_csv(output_dir / "power_spectrum_results.csv", index=False)
    
    # Create summary statistics
    summary_stats = {}
    
    # Height-based statistics
    for height in ['1m', '2m']:
        height_ar = ar_df[ar_df['sensor_height'] == height]
        height_psd = psd_df[psd_df['sensor_height'] == height]
        
        if not height_ar.empty and not height_psd.empty:
            summary_stats[f'{height}_mean_ar1'] = height_ar['ar1_coefficient'].mean()
            summary_stats[f'{height}_std_ar1'] = height_ar['ar1_coefficient'].std()
            summary_stats[f'{height}_mean_very_highfreq_fraction'] = height_psd['very_highfreq_fraction'].mean()
            summary_stats[f'{height}_std_very_highfreq_fraction'] = height_psd['very_highfreq_fraction'].std()
            summary_stats[f'{height}_mean_e_folding'] = height_ar['e_folding_time'].mean()
            summary_stats[f'{height}_std_e_folding'] = height_ar['e_folding_time'].std()
            summary_stats[f'{height}_n_sensors'] = len(height_ar)
    
    # Site-based statistics
    for site in ar_df['site_name'].unique():
        site_ar = ar_df[ar_df['site_name'] == site]
        site_psd = psd_df[psd_df['site_name'] == site]
        
        if not site_ar.empty and not site_psd.empty:
            summary_stats[f'{site}_mean_ar1'] = site_ar['ar1_coefficient'].mean()
            summary_stats[f'{site}_mean_very_highfreq_fraction'] = site_psd['very_highfreq_fraction'].mean()
            summary_stats[f'{site}_n_sensors'] = len(site_ar)
    
    # Overall statistics
    summary_stats['total_sensors'] = len(ar_df)
    summary_stats['overall_mean_ar1'] = ar_df['ar1_coefficient'].mean()
    summary_stats['overall_mean_very_highfreq_fraction'] = psd_df['very_highfreq_fraction'].mean()
    
    summary_df = pd.DataFrame([summary_stats])
    summary_df.to_csv(output_dir / "analysis_summary.csv", index=False)
    
    print("Analysis results saved:")
    print("  - Autoregression results: autoregression_results.csv")
    print("  - Power spectrum results: power_spectrum_results.csv") 
    print("  - Summary statistics: analysis_summary.csv")


