    for site_name, heights in ar_results.items():
        for height, sensors in heights.items():
            for sensor_result in sensors:
                ar1_coeff = sensor_result["ar1_coefficient"]
                e_folding = sensor_result["e_folding_time"]
                
                if height == "1m":
                    height_1m_ar1.append(ar1_coeff)
                    height_1m_efolding.append(e_folding)
                elif height == "2m":
                    height_2m_ar1.append(ar1_coeff)
                    height_2m_efolding.append(e_folding)
    
