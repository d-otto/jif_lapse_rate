def load_sensor_data(processed_dir, csv_deployment_path, use_csv_masking):
    """Load and organize sensor data from NetCDF files"""
    
    # Get all NetCDF files
    netcdf_files = list(processed_dir.glob("*.nc"))
    print(f"\nFound {len(netcdf_files)} NetCDF files")
    
    if not netcdf_files:
        return {}
    
    sensor_data = {}
    
    for nc_file in tqdm(netcdf_files, desc="Loading sensor datasets"):
        try:
            ds = xr.open_dataset(nc_file)
            
            # Extract metadata
            site_name = ds.attrs.get("site_name", "Unknown")
            sensor_height = ds.attrs.get("sensor_height", "Unknown")
            sensor_id = ds.attrs.get("sensor_id", "Unknown")
            
            # Create unique sensor identifier
            sensor_key = f"{site_name}_{sensor_height}_{sensor_id}"
            
            # Get temperature data
            temp_data = ds["temp_c"].dropna(dim="datetime")
            
            if len(temp_data) == 0:
                print(f"No valid temperature data for {sensor_key}")
                continue
            
            # Skip data from before 2025
            if temp_data.datetime.min().values < pd.Timestamp("2025-01-01"):
                print(f"Skipping {sensor_key} - data from before 2025")
                continue
            
            # Apply deployment masking if available
            deployed_mask = None
            if use_csv_masking:
                csv_filename = find_matching_csv_filename(
                    sensor_id, site_name, sensor_height, csv_deployment_path
                )
                
                if csv_filename:
                    try:
                        deployed_mask = mask_from_csv_deployment_periods(
                            temp_data.values, 
                            temp_data.datetime.values, 
                            csv_filename, 
                            csv_deployment_path
                        )
                    except Exception as e:
                        print(f"Could not apply CSV masking for {sensor_key}: {e}")
            
            # Store sensor information
            sensor_data[sensor_key] = {
                "temperature": temp_data,
                "site_name": site_name,
                "sensor_height": sensor_height,
                "sensor_id": sensor_id,
                "deployed_mask": deployed_mask,
                "file": nc_file.name
            }
            
        except Exception as e:
            print(f"Error loading {nc_file}: {e}")
            continue
    
    return sensor_data


def organize_data_by_site_height(sensor_data):
    """Organize sensor data by site and height for comparison"""
    
    organized = {}
    
    for sensor_key, data in sensor_data.items():
        site_name = data["site_name"]
        sensor_height = data["sensor_height"]
        
        # Create site key if it doesn't exist
        if site_name not in organized:
            organized[site_name] = {}
        
        # Create height key if it doesn't exist
        if sensor_height not in organized[site_name]:
            organized[site_name][sensor_height] = []
        
        # Add sensor data
        organized[site_name][sensor_height].append({
            "sensor_key": sensor_key,
            "data": data
        })
    
    # Print organization summary
    print("\nData organization summary:")
    for site_name, heights in organized.items():
        print(f"  Site {site_name}:")
        for height, sensors in heights.items():
            print(f"    {height}: {len(sensors)} sensors")
    
    return organized


def perform_autoregression_analysis(organized_data):
    """Perform autoregression analysis on temperature data"""
    
    print("\nPerforming autoregression analysis...")
    
    ar_results = {}
    
    for site_name, heights in organized_data.items():
        ar_results[site_name] = {}
        
        for height, sensors in heights.items():
            ar_results[site_name][height] = []
            
            for sensor_info in sensors:
                sensor_key = sensor_info["sensor_key"]
                temp_data = sensor_info["data"]["temperature"]
                
                try:
                    # Use 1-minute resolution data directly for high-frequency analysis
                    temp_minutely = temp_data.dropna(dim="datetime")
                    
                    # Limit to recent data (last 7 days) for computational efficiency
                    if len(temp_minutely) > 10080:  # 7 days * 24 hours * 60 minutes
                        temp_minutely = temp_minutely.isel(datetime=slice(-10080, None))
                    
                    if len(temp_minutely) < 600:  # Need at least 10 hours of 1-min data
                        print(f"Insufficient data for {sensor_key}: {len(temp_minutely)} points")
                        continue
                    
                    temp_values = temp_minutely.values
                    
                    # Remove longer-term trends but preserve high-frequency content
                    # Use a 6-hour moving average to remove low-frequency trends
                    window_size = min(360, len(temp_values) // 10)  # 6 hours in minutes
                    if window_size >= 3:
                        trend = np.convolve(temp_values, np.ones(window_size)/window_size, mode='same')
                        # Handle edges
                        trend[:window_size//2] = trend[window_size//2]
                        trend[-window_size//2:] = trend[-window_size//2-1]
                    else:
                        trend = np.mean(temp_values)
                    detrended = temp_values - trend
                    
                    # Calculate autocorrelation function for high-frequency analysis
                    # Focus on lags up to 6 hours (360 minutes)
                    max_lags = min(360, len(detrended) // 4)
                    autocorr = acf(detrended, nlags=max_lags, fft=True)
                    partial_autocorr = pacf(detrended, nlags=max_lags)
                    
                    # Fit autoregressive model (AR) for high-frequency dynamics
                    # Use higher order models to capture sensor response characteristics
                    max_order = min(60, len(detrended) // 50)  # Up to 1 hour of memory
                    aic_values = []
                    bic_values = []
                    
                    for order in range(1, max_order + 1):
                        try:
                            ar_model = AutoReg(detrended, lags=order, trend='c')
                            ar_fit = ar_model.fit()
                            aic_values.append(ar_fit.aic)
                            bic_values.append(ar_fit.bic)
                        except Exception:
                            aic_values.append(np.inf)
                            bic_values.append(np.inf)
                    
                    # Select optimal order
                    optimal_order_aic = int(np.argmin(aic_values) + 1)
                    optimal_order_bic = int(np.argmin(bic_values) + 1)
                    
                    # Fit final AR model with optimal order (using AIC)
                    ar_model = AutoReg(detrended, lags=optimal_order_aic, trend='c')
                    ar_fit = ar_model.fit()
                    
                    # Calculate residuals and perform diagnostics
                    residuals = ar_fit.resid
                    
                    # Calculate R-squared manually
                    y_mean = np.mean(detrended)
                    ss_tot = np.sum((detrended - y_mean) ** 2)
                    ss_res = np.sum(residuals ** 2)
                    r_squared = 1 - (ss_res / ss_tot) if ss_tot > 0 else 0
                    
                    # Ljung-Box test for residual autocorrelation
                    lb_test = acorr_ljungbox(residuals, lags=min(10, len(residuals)//5), return_df=True)
                    
                    # Calculate persistence metrics
                    # AR(1) coefficient for persistence measure
                    ar1_coeff = ar_fit.params[1] if len(ar_fit.params) > 1 else 0
                    
                    # Autocorrelation at lag 1
                    lag1_autocorr = autocorr[1] if len(autocorr) > 1 else 0
                    
                    # e-folding time (time for autocorrelation to decay to 1/e)
                    # This gives sensor response time in minutes
                    e_folding_time = calculate_e_folding_time(autocorr)
                    
                    # Calculate additional high-frequency metrics
                    # Time to 50% correlation (sensor half-life)
                    half_life = calculate_half_life_time(autocorr)
                    
                    # High-frequency variance (< 1 hour)
                    if len(detrended) > 60:
                        high_freq_var = np.var(np.diff(detrended))  # Minute-to-minute variance
                    else:
                        high_freq_var = 0
                    
                    ar_results[site_name][height].append({
                        "sensor_key": sensor_key,
                        "optimal_order_aic": optimal_order_aic,
                        "optimal_order_bic": optimal_order_bic,
                        "aic_values": aic_values,
                        "bic_values": bic_values,
                        "ar_coefficients": ar_fit.params,
                        "ar1_coefficient": ar1_coeff,
                        "autocorr": autocorr,
                        "partial_autocorr": partial_autocorr,
                        "lag1_autocorr": lag1_autocorr,
                        "e_folding_time": e_folding_time,
                        "half_life_time": half_life,
                        "high_freq_variance": high_freq_var,
                        "residuals": residuals,
                        "ljung_box_pvalue": lb_test['lb_pvalue'].min(),
                        "r_squared": r_squared,
                        "aic": ar_fit.aic,
                        "bic": ar_fit.bic,
                        "n_obs": len(detrended),
                        "detrended_data": detrended,
                        "datetime": temp_minutely.datetime.values
                    })
                    
                except Exception as e:
                    print(f"Error in AR analysis for {sensor_key}: {e}")
                    continue
    
    return ar_results


def calculate_e_folding_time(autocorr):
    """Calculate e-folding time from autocorrelation function"""
    
    try:
        # Find where autocorrelation drops below 1/e ≈ 0.368
        threshold = 1.0 / np.e
        
        # Start from lag 1 (skip lag 0 which is always 1)
        for i in range(1, len(autocorr)):
            if autocorr[i] < threshold:
                return i
        
        # If never drops below threshold, return length
        return len(autocorr)
    
    except Exception:
        return np.nan


def calculate_half_life_time(autocorr):
    """Calculate half-life time (50% correlation) from autocorrelation function"""
    
    try:
        # Find where autocorrelation drops below 0.5
        threshold = 0.5
        
        # Start from lag 1 (skip lag 0 which is always 1)
        for i in range(1, len(autocorr)):
            if autocorr[i] < threshold:
                return i
        
        # If never drops below threshold, return length
        return len(autocorr)
    
    except Exception:
        return np.nan


def perform_power_spectral_analysis(organized_data):
    """Perform power spectral analysis using WOSA method"""
    
    print("\nPerforming power spectral analysis using WOSA...")
    
    psd_results = {}
    
    for site_name, heights in organized_data.items():
        psd_results[site_name] = {}
        
        for height, sensors in heights.items():
            psd_results[site_name][height] = []
            
            for sensor_info in sensors:
                sensor_key = sensor_info["sensor_key"]
                temp_data = sensor_info["data"]["temperature"]
                
                try:
                    # Use 1-minute resolution data directly for high-frequency analysis
                    temp_minutely = temp_data.dropna(dim="datetime")
                    
                    # Limit to recent data (last 7 days) for computational efficiency
                    if len(temp_minutely) > 10080:  # 7 days * 24 hours * 60 minutes
                        temp_minutely = temp_minutely.isel(datetime=slice(-10080, None))
                    
                    if len(temp_minutely) < 600:  # Need at least 10 hours of 1-min data
                        print(f"Insufficient data for {sensor_key}: {len(temp_minutely)} points")
                        continue
                    
                    temp_values = temp_minutely.values
                    
                    # Remove longer-term trends but preserve high-frequency content
                    # Use a 6-hour moving average to remove low-frequency trends
                    window_size = min(360, len(temp_values) // 10)  # 6 hours in minutes
                    if window_size >= 3:
                        trend = np.convolve(temp_values, np.ones(window_size)/window_size, mode='same')
                        # Handle edges
                        trend[:window_size//2] = trend[window_size//2]
                        trend[-window_size//2:] = trend[-window_size//2-1]
                    else:
                        trend = np.mean(temp_values)
                    detrended = temp_values - trend
                    
                    # Sampling frequency (1 minute = 1/60 Hz, but we work in cycles/minute)
                    fs = 1.0  # 1 sample per minute
                    
                    # WOSA parameters
                    # Window length: aim for ~256 points or 1/8 of data, whichever is smaller
                    nperseg = min(256, len(detrended) // 8)
                    if nperseg < 32:
                        nperseg = min(32, len(detrended) // 4)
                    
                    # 50% overlap as requested
                    noverlap = nperseg // 2
                    
                    # Calculate power spectral density using Welch's method (WOSA)
                    frequencies, psd = signal.welch(
                        detrended,
                        fs=fs,
                        window='hann',
                        nperseg=nperseg,
                        noverlap=noverlap,
                        detrend='linear',
                        return_onesided=True
                    )
                    
                    # Convert frequencies to periods (minutes)
                    # Avoid division by zero
                    periods = np.where(frequencies > 0, 1.0 / frequencies, np.inf)
                    
                    # Calculate integrated power in high-frequency bands (focus on <6 hours)
                    # Very high frequency (< 10 minutes) - sensor noise/response
                    very_highfreq_mask = periods < 10
                    very_highfreq_power = np.trapezoid(psd[very_highfreq_mask], frequencies[very_highfreq_mask]) if np.any(very_highfreq_mask) else 0
                    
                    # High frequency (10 minutes - 1 hour) - rapid fluctuations
                    highfreq_mask = (periods >= 10) & (periods < 60)
                    highfreq_power = np.trapezoid(psd[highfreq_mask], frequencies[highfreq_mask]) if np.any(highfreq_mask) else 0
                    
                    # Medium frequency (1-6 hours) - short-term variations
                    medfreq_mask = (periods >= 60) & (periods < 360)
                    medfreq_power = np.trapezoid(psd[medfreq_mask], frequencies[medfreq_mask]) if np.any(medfreq_mask) else 0
                    
                    # Low frequency (> 6 hours) - long-term variations
                    lowfreq_mask = periods >= 360
                    lowfreq_power = np.trapezoid(psd[lowfreq_mask], frequencies[lowfreq_mask]) if np.any(lowfreq_mask) else 0
                    
                    # Total power
                    total_power = np.trapezoid(psd, frequencies)
                    
                    # Find peak frequencies
                    peak_indices = signal.find_peaks(psd, height=np.percentile(psd, 90))[0]
                    peak_frequencies = frequencies[peak_indices]
                    peak_periods = periods[peak_indices]
                    peak_powers = psd[peak_indices]
                    
                    psd_results[site_name][height].append({
                        "sensor_key": sensor_key,
                        "frequencies": frequencies,
                        "periods": periods,
                        "psd": psd,
                        "nperseg": nperseg,
                        "noverlap": noverlap,
                        "very_highfreq_power": very_highfreq_power,
                        "highfreq_power": highfreq_power,
                        "medfreq_power": medfreq_power,
                        "lowfreq_power": lowfreq_power,
                        "total_power": total_power,
                        "very_highfreq_fraction": float(very_highfreq_power / total_power) if float(total_power) > 0 else 0.0,
                        "highfreq_fraction": float(highfreq_power / total_power) if float(total_power) > 0 else 0.0,
                        "medfreq_fraction": float(medfreq_power / total_power) if float(total_power) > 0 else 0.0,
                        "lowfreq_fraction": float(lowfreq_power / total_power) if float(total_power) > 0 else 0.0,
                        "peak_frequencies": peak_frequencies,
                        "peak_periods": peak_periods,
                        "peak_powers": peak_powers,
                        "n_obs": len(detrended),
                        "detrended_data": detrended,
                        "datetime": temp_minutely.datetime.values
                    })
                    
                except Exception as e:
                    print(f"Error in PSD analysis for {sensor_key}: {e}")
                    continue
    
    return psd_results


