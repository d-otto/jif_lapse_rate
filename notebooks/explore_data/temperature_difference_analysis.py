def analyze_daily_cycles(times, temp_2m, temp_1m, subtract_mean=True):
    """Analyze daily temperature cycles from noon to noon"""

    # Convert to pandas for easier manipulation
    df = pd.DataFrame({"datetime": times, "temp_2m": temp_2m, "temp_1m": temp_1m})
    df.set_index("datetime", inplace=True)

    # Find noon times (12:00) for splitting days
    all_noons = []
    start_date = df.index[0].date()
    end_date = df.index[-1].date()

    current_date = start_date
    while current_date <= end_date:
        noon_time = pd.Timestamp(
            year=current_date.year,
            month=current_date.month,
            day=current_date.day,
            hour=12,
            minute=0,
        )
        if noon_time >= df.index[0] and noon_time <= df.index[-1]:
            all_noons.append(noon_time)
        current_date = current_date + pd.Timedelta(days=1)

    if len(all_noons) < 2:
        return None

    # Split data into noon-to-noon periods
    daily_data = []
    for i in range(len(all_noons) - 1):
        start_noon = all_noons[i]
        end_noon = all_noons[i + 1]

        # Extract 24-hour period
        day_data = df[(df.index >= start_noon) & (df.index < end_noon)].copy()

        if len(day_data) < 10:  # Skip days with too little data
            continue

        # Calculate hours from noon
        day_data["hours_from_noon"] = (
            day_data.index - start_noon
        ).total_seconds() / 3600

        # Subtract daily mean if requested
        if subtract_mean:
            # Use pooled mean of both sensors
            pooled_mean = pd.concat([day_data["temp_2m"], day_data["temp_1m"]]).mean()
            day_data["temp_2m_detrended"] = day_data["temp_2m"] - pooled_mean
            day_data["temp_1m_detrended"] = day_data["temp_1m"] - pooled_mean
        else:
            day_data["temp_2m_detrended"] = day_data["temp_2m"]
            day_data["temp_1m_detrended"] = day_data["temp_1m"]

        daily_data.append(day_data)

    if len(daily_data) == 0:
        return None

    # Create common hourly grid (0-24 hours from noon)
    hour_grid = np.arange(0, 24, 0.25)  # 15-minute intervals

    # Interpolate each day to common grid
    interpolated_2m = []
    interpolated_1m = []

    for day_data in daily_data:
        # Interpolate to hour grid
        temp_2m_interp = np.interp(
            hour_grid, day_data["hours_from_noon"], day_data["temp_2m_detrended"]
        )
        temp_1m_interp = np.interp(
            hour_grid, day_data["hours_from_noon"], day_data["temp_1m_detrended"]
        )

        interpolated_2m.append(temp_2m_interp)
        interpolated_1m.append(temp_1m_interp)

    # Convert to arrays
    interpolated_2m = np.array(interpolated_2m)
    interpolated_1m = np.array(interpolated_1m)

    # Calculate statistics
    mean_2m = np.mean(interpolated_2m, axis=0)
    mean_1m = np.mean(interpolated_1m, axis=0)
    median_2m = np.median(interpolated_2m, axis=0)
    median_1m = np.median(interpolated_1m, axis=0)
    std_2m = np.std(interpolated_2m, axis=0)
    std_1m = np.std(interpolated_1m, axis=0)

    return {
        "hour_grid": hour_grid,
        "mean_2m": mean_2m,
        "mean_1m": mean_1m,
        "median_2m": median_2m,
        "median_1m": median_1m,
        "std_2m": std_2m,
        "std_1m": std_1m,
        "n_days": len(daily_data),
    }


def plot_daily_cycles(ax, analysis_data, title, y_range=None):
    """Plot the daily cycle analysis results"""

    hour_grid = analysis_data["hour_grid"]
    mean_2m = analysis_data["mean_2m"]
    mean_1m = analysis_data["mean_1m"]
    std_2m = analysis_data["std_2m"]
    std_1m = analysis_data["std_1m"]
    n_days = analysis_data["n_days"]

    # Plot mean curves
    ax.plot(
        hour_grid, mean_2m, color="red", linewidth=2, label=f"2m Mean (n={n_days} days)"
    )
    ax.plot(
        hour_grid,
        mean_1m,
        color="blue",
        linewidth=2,
        label=f"1m Mean (n={n_days} days)",
    )

    # Plot standard deviation as lines instead of shaded areas
    ax.plot(
        hour_grid,
        mean_2m + std_2m,
        color="red",
        linewidth=1,
        linestyle=":",
        alpha=0.7,
        label="2m +1σ",
    )
    ax.plot(
        hour_grid,
        mean_2m - std_2m,
        color="red",
        linewidth=1,
        linestyle=":",
        alpha=0.7,
        label="2m -1σ",
    )
    ax.plot(
        hour_grid,
        mean_1m + std_1m,
        color="blue",
        linewidth=1,
        linestyle=":",
        alpha=0.7,
        label="1m +1σ",
    )
    ax.plot(
        hour_grid,
        mean_1m - std_1m,
        color="blue",
        linewidth=1,
        linestyle=":",
        alpha=0.7,
        label="1m -1σ",
    )

    # Shade areas where 2m > 1m (temperature inversion)
    inversion_mask = mean_2m > mean_1m
    if np.any(inversion_mask):
        ax.fill_between(
            hour_grid,
            mean_1m,
            mean_2m,
            where=inversion_mask,
            alpha=0.3,
            color="grey",
            label="Inverted (2m > 1m)",
        )

    # Add 0-degree reference line
    ax.axhline(y=0, color="black", linestyle="--", alpha=0.8, linewidth=1)

    # Set consistent y-axis range if provided
    if y_range is not None:
        # Center the y-axis around the data range
        current_min = min(np.min(mean_2m - std_2m), np.min(mean_1m - std_1m))
        current_max = max(np.max(mean_2m + std_2m), np.max(mean_1m + std_1m))
        current_center = (current_min + current_max) / 2

        # Set new range with same magnitude as raw data
        new_min = current_center - y_range / 2
        new_max = current_center + y_range / 2
        ax.set_ylim(new_min, new_max)

    # Formatting
    ax.set_title(title)
    ax.set_xlabel("Hours from Noon")
    ax.set_ylabel("Temperature (°C)")
    ax.set_xlim(0, 24)
    ax.grid(True, alpha=0.3)
    ax.legend(loc="upper right", fontsize=8)

    # Set x-axis ticks
    ax.set_xticks([0, 6, 12, 18, 24])
    ax.set_xticklabels(["Noon", "6PM", "Midnight", "6AM", "Noon"])


def create_deployment_qc_plots(
    site_name,
    sensor_id_2m,
    sensor_id_1m,
    temp_2m,
    temp_1m,
    times,
    deployed_2m,
    deployed_1m,
    output_dir,
    method_2m="variance",
    method_1m="variance",
    threshold_2m=0.1,
    threshold_1m=0.1,
    window_hours_2m=6.0,
    window_hours_1m=6.0,
    min_deployment_hours=3.0,
):
    """Create and save QC plots showing deployment detection metrics."""

    # Calculate metrics for both sensors to show on plots
    # Use the same methods as used for deployment detection

    # Calculate 2m sensor metric
    ts_2m = pd.Series(temp_2m, index=times)
    if method_2m == "variance":
        metric_2m = _calculate_variance_metric(ts_2m, window_hours_2m)
    elif method_2m == "wosa":
        metric_2m = _calculate_wosa_metric(ts_2m, window_hours_2m)
    elif method_2m == "autocorr":
        metric_2m = _calculate_autocorr_metric(ts_2m, window_hours_2m, 2.0)
    elif method_2m == "gradient":
        metric_2m = _calculate_gradient_metric(ts_2m, window_hours_2m)
    else:
        raise ValueError(f"Unknown method: {method_2m}")

    # Calculate 1m sensor metric
    ts_1m = pd.Series(temp_1m, index=times)
    if method_1m == "variance":
        metric_1m = _calculate_variance_metric(ts_1m, window_hours_1m)
    elif method_1m == "wosa":
        metric_1m = _calculate_wosa_metric(ts_1m, window_hours_1m)
    elif method_1m == "autocorr":
        metric_1m = _calculate_autocorr_metric(ts_1m, window_hours_1m, 2.0)
    elif method_1m == "gradient":
        metric_1m = _calculate_gradient_metric(ts_1m, window_hours_1m)
    else:
        raise ValueError(f"Unknown method: {method_1m}")

    # Calculate raw deployment masks (before morphological cleaning) for comparison
    raw_deployed_2m = metric_2m > threshold_2m
    raw_deployed_1m = metric_1m > threshold_1m

    # Debug output
    print(
        f"  Debug - 2m {method_2m} metric range: {metric_2m.min():.4f} to {metric_2m.max():.4f}"
    )
    print(
        f"  Debug - 1m {method_1m} metric range: {metric_1m.min():.4f} to {metric_1m.max():.4f}"
    )
    print(
        f"  Debug - metric_2m has {metric_2m.count()} non-NaN values out of {len(metric_2m)}"
    )
    print(
        f"  Debug - metric_1m has {metric_1m.count()} non-NaN values out of {len(metric_1m)}"
    )
    print(f"  Debug - Raw vs cleaned deployment detection:")
    print(
        f"    2m: {np.sum(raw_deployed_2m)}/{len(raw_deployed_2m)} raw → {np.sum(deployed_2m)}/{len(deployed_2m)} cleaned"
    )
    print(
        f"    1m: {np.sum(raw_deployed_1m)}/{len(raw_deployed_1m)} raw → {np.sum(deployed_1m)}/{len(deployed_1m)} cleaned"
    )

    # Create figure with 4 subplots
    fig, axes = plt.subplots(2, 2, figsize=(16, 12))
    fig.suptitle(
        f"Deployment Detection QC: {site_name}\n"
        f"2m Sensor: {sensor_id_2m} | 1m Sensor: {sensor_id_1m}",
        fontsize=14,
        fontweight="bold",
    )

    # Plot 1: 2m sensor temperature with deployment periods
    ax = axes[0, 0]
    ax.plot(times, temp_2m, "b-", alpha=0.7, linewidth=0.8, label="2m Temperature")

    # Highlight non-deployed periods
    non_deployed_2m = ~deployed_2m
    if np.any(non_deployed_2m):
        non_deployed_diff = np.diff(
            np.concatenate(([False], non_deployed_2m, [False])).astype(int)
        )
        starts = np.where(non_deployed_diff == 1)[0]
        ends = np.where(non_deployed_diff == -1)[0]

        for i, (start, end) in enumerate(zip(starts, ends)):
            ax.axvspan(
                times[start],
                times[end - 1] if end < len(times) else times[-1],
                alpha=0.3,
                color="red",
                label="Not deployed" if i == 0 else "",
            )

    ax.set_title("2m Sensor Temperature & Deployment")
    ax.set_ylabel("Temperature (°C)")
    ax.legend()
    ax.grid(True, alpha=0.3)

    # Plot 2: 1m sensor temperature with deployment periods
    ax = axes[0, 1]
    ax.plot(times, temp_1m, "g-", alpha=0.7, linewidth=0.8, label="1m Temperature")

    # Highlight non-deployed periods
    non_deployed_1m = ~deployed_1m
    if np.any(non_deployed_1m):
        non_deployed_diff = np.diff(
            np.concatenate(([False], non_deployed_1m, [False])).astype(int)
        )
        starts = np.where(non_deployed_diff == 1)[0]
        ends = np.where(non_deployed_diff == -1)[0]

        for i, (start, end) in enumerate(zip(starts, ends)):
            ax.axvspan(
                times[start],
                times[end - 1] if end < len(times) else times[-1],
                alpha=0.3,
                color="red",
                label="Not deployed" if i == 0 else "",
            )

    ax.set_title("1m Sensor Temperature & Deployment")
    ax.set_ylabel("Temperature (°C)")
    ax.legend()
    ax.grid(True, alpha=0.3)

    # Plot 3: 2m sensor metric with threshold
    ax = axes[1, 0]
    ax.plot(
        metric_2m.index,
        metric_2m.values,
        "b-",
        alpha=0.8,
        linewidth=1,
        label=f"{method_2m.title()} Metric",
    )
    ax.axhline(
        threshold_2m,
        color="r",
        linestyle="--",
        alpha=0.7,
        linewidth=2,
        label=f"Threshold ({threshold_2m})",
    )
    # Show raw deployment periods in light green
    ax.fill_between(
        metric_2m.index,
        metric_2m.values,
        threshold_2m,
        where=np.array(raw_deployed_2m),
        alpha=0.2,
        color="lightgreen",
        label="Raw Deployed",
    )

    # Show cleaned deployment periods in darker green
    ax.fill_between(
        metric_2m.index,
        metric_2m.values,
        threshold_2m,
        where=np.array(deployed_2m),
        alpha=0.4,
        color="green",
        label="Cleaned Deployed",
    )

    # Set appropriate y-axis label based on method
    ylabel_2m = _get_ylabel_for_method(method_2m)
    ax.set_title(f"2m Sensor: {method_2m.title()} Metric")
    ax.set_ylabel(ylabel_2m)
    ax.set_xlabel("Time")
    ax.legend()
    ax.grid(True, alpha=0.3)

    # Plot 4: 1m sensor metric with threshold
    ax = axes[1, 1]
    ax.plot(
        metric_1m.index,
        metric_1m.values,
        "g-",
        alpha=0.8,
        linewidth=1,
        label=f"{method_1m.title()} Metric",
    )
    ax.axhline(
        threshold_1m,
        color="r",
        linestyle="--",
        alpha=0.7,
        linewidth=2,
        label=f"Threshold ({threshold_1m})",
    )
    # Show raw deployment periods in light green
    ax.fill_between(
        metric_1m.index,
        metric_1m.values,
        threshold_1m,
        where=np.array(raw_deployed_1m),
        alpha=0.2,
        color="lightgreen",
        label="Raw Deployed",
    )

    # Show cleaned deployment periods in darker green
    ax.fill_between(
        metric_1m.index,
        metric_1m.values,
        threshold_1m,
        where=np.array(deployed_1m),
        alpha=0.4,
        color="green",
        label="Cleaned Deployed",
    )

    # Set appropriate y-axis label based on method
    ylabel_1m = _get_ylabel_for_method(method_1m)
    ax.set_title(f"1m Sensor: {method_1m.title()} Metric")
    ax.set_ylabel(ylabel_1m)
    ax.set_xlabel("Time")
    ax.legend()
    ax.grid(True, alpha=0.3)

    # Format x-axis for all plots
    for ax in axes.flat:
        ax.xaxis.set_major_locator(mdates.WeekdayLocator(interval=1))
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%m/%d"))
        ax.tick_params(axis="x", rotation=45)

    plt.tight_layout()

    # Save QC plot
    safe_site_name = "".join(
        c for c in site_name if c.isalnum() or c in (" ", "-", "_")
    ).rstrip()
    qc_output_file = output_dir / f"{safe_site_name}_deployment_qc.png"
    plt.savefig(qc_output_file, dpi=300, bbox_inches="tight")
    plt.close()

    print(f"  QC plot saved: {qc_output_file}")


def _get_ylabel_for_method(method):
    """Get appropriate y-axis label for each metric method."""
    labels = {
        "variance": "Temperature Std Dev (°C)",
        "wosa": "High-Freq RMS Variability (°C)",
        "autocorr": "Inverted Autocorrelation",
        "gradient": "Gradient Std Dev (°C/timestep)",
    }
    return labels.get(method, "Metric Value")


