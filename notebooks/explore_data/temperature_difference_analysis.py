    ax.set_ylabel("Correlation Coefficient")
    ax.set_ylim(-1, 1)
    ax.grid(True, alpha=0.3)
    ax.legend(loc="lower right")

    # Add colorbar for time of day
    sm = cm.ScalarMappable(cmap="twilight", norm=Normalize(vmin=0, vmax=24))
