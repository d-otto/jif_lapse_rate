    ax.axhline(y=0.0, color="black", linestyle="--", alpha=0.5, linewidth=1)
    ax.axvline(
        x=0.0,
        color="black",
        linestyle="--",
        alpha=0.5,
        linewidth=1,
        label="No Inversion",
    )

    # Formatting
    ax.set_title("Temperature Correlation vs Inversion Strength")
