def process_site_pair(
    site1_name,
    site1_sensors,
    site2_name,
    site2_sensors,
    site_elevations,
    csv_deployment_path,
    use_csv_masking,
):
    """Process a single site pair and return analysis data"""

    # Extract datasets
    ds1_1m = site1_sensors["1m"]["dataset"]
    ds1_2m = site1_sensors["2m"]["dataset"]
    ds2_1m = site2_sensors["1m"]["dataset"]
    ds2_2m = site2_sensors["2m"]["dataset"]

    # Get temperature data
    temp1_1m = ds1_1m["temp_c"].dropna("datetime")
    temp1_2m = ds1_2m["temp_c"].dropna("datetime")
    temp2_1m = ds2_1m["temp_c"].dropna("datetime")
    temp2_2m = ds2_2m["temp_c"].dropna("datetime")

    # Find overlapping time period
    start_time = max(
        temp1_1m.datetime.min().values,
        temp1_2m.datetime.min().values,
        temp2_1m.datetime.min().values,
        temp2_2m.datetime.min().values,
    )
    end_time = min(
        temp1_1m.datetime.max().values,
        temp1_2m.datetime.max().values,
        temp2_1m.datetime.max().values,
        temp2_2m.datetime.max().values,
    )

    if start_time >= end_time:
        return None

    # Create common time grid
    common_times = pd.date_range(start_time, end_time, freq="10min")

    # Interpolate all sensors to common time grid
    temp1_1m_interp = temp1_1m.interp(datetime=common_times, method="linear")
    temp1_2m_interp = temp1_2m.interp(datetime=common_times, method="linear")
    temp2_1m_interp = temp2_1m.interp(datetime=common_times, method="linear")
    temp2_2m_interp = temp2_2m.interp(datetime=common_times, method="linear")

    # Drop NaN values
    valid_mask = ~(
        np.isnan(temp1_1m_interp.values)
        | np.isnan(temp1_2m_interp.values)
        | np.isnan(temp2_1m_interp.values)
        | np.isnan(temp2_2m_interp.values)
    )

    times_valid = common_times[valid_mask]
    temp1_1m_valid = temp1_1m_interp.values[valid_mask]
    temp1_2m_valid = temp1_2m_interp.values[valid_mask]
    temp2_1m_valid = temp2_1m_interp.values[valid_mask]
    temp2_2m_valid = temp2_2m_interp.values[valid_mask]

    if len(times_valid) == 0:
        return None

    # Apply deployment masking if available
    if use_csv_masking:
        deployed_mask = apply_deployment_masking(
            [ds1_1m, ds1_2m, ds2_1m, ds2_2m],
            [
                site1_sensors["1m"],
                site1_sensors["2m"],
                site2_sensors["1m"],
                site2_sensors["2m"],
            ],
            times_valid,
            [temp1_1m_valid, temp1_2m_valid, temp2_1m_valid, temp2_2m_valid],
            csv_deployment_path,
            site1_name,
            site2_name,
        )
    else:
        deployed_mask = np.ones(len(times_valid), dtype=bool)

    # Resample to hourly averages
    temp_arrays = [temp1_1m_valid, temp1_2m_valid, temp2_1m_valid, temp2_2m_valid]
    times_hourly, temp_arrays_hourly, deployed_mask_hourly = resample_to_hourly(
        times_valid, temp_arrays, deployed_mask
    )

    if times_hourly is None:
        return None

    # Extract hourly temperature data
    temp1_1m_hourly, temp1_2m_hourly, temp2_1m_hourly, temp2_2m_hourly = (
        temp_arrays_hourly
    )

    # Calculate lapse rate
    elevation1 = site_elevations.get(site1_name, 0)
    elevation2 = site_elevations.get(site2_name, 0)
    elevation_diff_km = abs(elevation1 - elevation2) / 1000.0

    if elevation_diff_km > 0:
        if elevation1 > elevation2:
            lapse_rate_hourly = (temp1_2m_hourly - temp2_2m_hourly) / elevation_diff_km
        else:
            lapse_rate_hourly = (temp2_2m_hourly - temp1_2m_hourly) / elevation_diff_km
    else:
        lapse_rate_hourly = np.zeros_like(temp1_2m_hourly)

    # Calculate correlation
    correlation = np.corrcoef(temp1_2m_hourly, temp2_2m_hourly)[0, 1]

    # Calculate temperature differences
    temp_diff1 = temp1_2m_hourly - temp1_1m_hourly
    temp_diff2 = temp2_2m_hourly - temp2_1m_hourly

    return {
        "lapse_rate": lapse_rate_hourly,
        "correlation": correlation,
        "temp_diffs": (temp_diff1, temp_diff2),
        "times": times_hourly,
        "elevation_diff": elevation_diff_km,
        "temps": (temp1_1m_hourly, temp1_2m_hourly, temp2_1m_hourly, temp2_2m_hourly),
    }


def resample_to_hourly(times, temp_arrays, deployed_mask):
    """Resample temperature data to 1-hour averages"""

    df = pd.DataFrame(
        {
            "datetime": times,
            "temp1_1m": temp_arrays[0],
            "temp1_2m": temp_arrays[1],
            "temp2_1m": temp_arrays[2],
            "temp2_2m": temp_arrays[3],
            "deployed": deployed_mask,
        }
    )
    df.set_index("datetime", inplace=True)

    # Only use deployed data for resampling
    df_deployed = df[df["deployed"]].drop(columns=["deployed"])

    if len(df_deployed) == 0:
        return None, None, None

    # Resample to hourly averages
    df_hourly = (
        df_deployed.resample("1H")
        .agg(
            {
                "temp1_1m": "mean",
                "temp1_2m": "mean",
                "temp2_1m": "mean",
                "temp2_2m": "mean",
            }
        )
        .dropna()
    )

    if len(df_hourly) == 0:
        return None, None, None

    # Extract hourly data
    times_hourly = df_hourly.index.values
    temp_arrays_hourly = [
        df_hourly["temp1_1m"].values,
        df_hourly["temp1_2m"].values,
        df_hourly["temp2_1m"].values,
        df_hourly["temp2_2m"].values,
    ]
    deployed_mask_hourly = np.ones(len(times_hourly), dtype=bool)

    return times_hourly, temp_arrays_hourly, deployed_mask_hourly


def apply_deployment_masking(
    datasets,
    sensor_info,
    times_valid,
    temp_arrays,
    csv_deployment_path,
    site1_name,
    site2_name,
):
    """Apply deployment masking to all sensors"""

    deployed_masks = []
    for ds, sensor_info_item, temp_array in zip(datasets, sensor_info, temp_arrays):
        site_name = ds.attrs.get("site_name", "Unknown")
        height = ds.attrs.get("sensor_height", "Unknown")
        sensor_id = ds.attrs.get("sensor_id", "Unknown")

        csv_filename = find_matching_csv_filename(
            sensor_id, site_name, height, csv_deployment_path
        )

        if csv_filename:
            deployed = mask_from_csv_deployment_periods(
                temp_array, times_valid, csv_filename, csv_deployment_path
            )
            deployed_masks.append(deployed)
        else:
            deployed_masks.append(np.ones(len(times_valid), dtype=bool))

    # Combined mask: all sensors must be deployed
    combined_mask = np.all(deployed_masks, axis=0)
    return combined_mask


def calculate_site_temperature_data(
    sites, sites_with_both, site_elevations, csv_deployment_path, use_csv_masking
):
    """Calculate mean temperatures by time period for all sites in the group"""

    site_temp_data = {}

    for site_name in sites:
        if site_name not in sites_with_both:
            continue

        try:
            # Get sensor data
            ds_1m = sites_with_both[site_name]["1m"]["dataset"]
            ds_2m = sites_with_both[site_name]["2m"]["dataset"]

            # Get temperature data
            temp_1m = ds_1m["temp_c"].dropna("datetime")
            temp_2m = ds_2m["temp_c"].dropna("datetime")

            # Find overlapping time period
            start_time = max(
                temp_1m.datetime.min().values, temp_2m.datetime.min().values
            )
            end_time = min(temp_1m.datetime.max().values, temp_2m.datetime.max().values)

            if start_time >= end_time:
                continue

            # Create common time grid (10-minute resolution)
            common_times = pd.date_range(start_time, end_time, freq="10min")

            # Interpolate to common time grid
            temp_1m_interp = temp_1m.interp(datetime=common_times, method="linear")
            temp_2m_interp = temp_2m.interp(datetime=common_times, method="linear")

            # Remove NaN values
            valid_mask = ~(
                np.isnan(temp_1m_interp.values) | np.isnan(temp_2m_interp.values)
            )

            if not np.any(valid_mask):
                continue

            times_valid = common_times[valid_mask]
            temp_1m_valid = temp_1m_interp.values[valid_mask]
            temp_2m_valid = temp_2m_interp.values[valid_mask]

            # Apply deployment masking if available
            if use_csv_masking:
                deployed_mask = apply_deployment_masking(
                    [ds_1m, ds_2m],
                    [
                        sites_with_both[site_name]["1m"],
                        sites_with_both[site_name]["2m"],
                    ],
                    times_valid,
                    [temp_1m_valid, temp_2m_valid],
                    csv_deployment_path,
                    site_name,
                    site_name,
                )
            else:
                deployed_mask = np.ones(len(times_valid), dtype=bool)

            # Filter to deployed periods only
            if not np.any(deployed_mask):
                continue

            times_deployed = times_valid[deployed_mask]
            temp_1m_deployed = temp_1m_valid[deployed_mask]
            temp_2m_deployed = temp_2m_valid[deployed_mask]

            # Calculate mean temperatures and standard deviations by time period
            temp_means = {}
            temp_stds = {}

            for period_name, (start_hour, end_hour) in TIME_PERIODS.items():
                if period_name == "nighttime" and end_hour < start_hour:
                    # Handle wrap-around for nighttime (20:00 to 04:00)
                    time_mask = (pd.Series(times_deployed).dt.hour >= start_hour) | (
                        pd.Series(times_deployed).dt.hour < end_hour
                    )
                else:
                    # Normal time range
                    time_mask = (pd.Series(times_deployed).dt.hour >= start_hour) & (
                        pd.Series(times_deployed).dt.hour < end_hour
                    )

                if np.any(time_mask):
                    temp_means[period_name] = {
                        "1m": np.mean(temp_1m_deployed[time_mask]),
                        "2m": np.mean(temp_2m_deployed[time_mask]),
                    }
                    temp_stds[period_name] = {
                        "1m": np.std(temp_1m_deployed[time_mask], ddof=1),
                        "2m": np.std(temp_2m_deployed[time_mask], ddof=1),
                    }
                else:
                    temp_means[period_name] = {"1m": np.nan, "2m": np.nan}
                    temp_stds[period_name] = {"1m": np.nan, "2m": np.nan}

            site_temp_data[site_name] = {
                "elevation": site_elevations.get(site_name, 0),
                "temp_means": temp_means,
                "temp_stds": temp_stds,
            }

        except Exception as e:
            print(f"    Error processing {site_name} temperature data: {e}")
            continue

    return site_temp_data


def calculate_lapse_rates_multiple_resolutions(
    sites, sites_with_both, site_elevations, csv_deployment_path, use_csv_masking
):
    """Calculate lapse rates for multiple temporal resolutions"""

    lapse_rate_data = {res: [] for res in TEMPORAL_RESOLUTIONS}

    # Process all site pairs
    site_pairs = list(combinations(sites, 2))

    for site1, site2 in site_pairs:
        if site1 not in sites_with_both or site2 not in sites_with_both:
            continue

        try:
            # Process the site pair for different resolutions
            pair_data = process_site_pair_multiple_resolutions(
                site1,
                sites_with_both[site1],
                site2,
                sites_with_both[site2],
                site_elevations,
                csv_deployment_path,
                use_csv_masking,
            )

            if pair_data:
                for resolution in TEMPORAL_RESOLUTIONS:
                    if resolution in pair_data:
                        lapse_rate_data[resolution].extend(pair_data[resolution])

        except Exception as e:
            print(f"    Error processing {site1}-{site2} for multiple resolutions: {e}")
            continue

    return lapse_rate_data


def process_site_pair_multiple_resolutions(
    site1_name,
    site1_sensors,
    site2_name,
    site2_sensors,
    site_elevations,
    csv_deployment_path,
    use_csv_masking,
):
    """Process site pair for multiple temporal resolutions"""

    # Extract datasets
    ds1_1m = site1_sensors["1m"]["dataset"]
    ds1_2m = site1_sensors["2m"]["dataset"]
    ds2_1m = site2_sensors["1m"]["dataset"]
    ds2_2m = site2_sensors["2m"]["dataset"]

    # Get temperature data
    temp1_1m = ds1_1m["temp_c"].dropna("datetime")
    temp1_2m = ds1_2m["temp_c"].dropna("datetime")
    temp2_1m = ds2_1m["temp_c"].dropna("datetime")
    temp2_2m = ds2_2m["temp_c"].dropna("datetime")

    # Find overlapping time period
    start_time = max(
        temp1_1m.datetime.min().values,
        temp1_2m.datetime.min().values,
        temp2_1m.datetime.min().values,
        temp2_2m.datetime.min().values,
    )
    end_time = min(
        temp1_1m.datetime.max().values,
        temp1_2m.datetime.max().values,
        temp2_1m.datetime.max().values,
        temp2_2m.datetime.max().values,
    )

    if start_time >= end_time:
        return None

    # Calculate elevation difference
    elevation1 = site_elevations.get(site1_name, 0)
    elevation2 = site_elevations.get(site2_name, 0)
    elevation_diff_km = abs(elevation1 - elevation2) / 1000.0

    if elevation_diff_km == 0:
        return None

    result_data = {}

    # Process each temporal resolution
    for resolution in TEMPORAL_RESOLUTIONS:
        try:
            # Create time grid for this resolution
            common_times = pd.date_range(start_time, end_time, freq=resolution)

            # Interpolate all sensors to common time grid
            temp1_1m_interp = temp1_1m.interp(datetime=common_times, method="linear")
            temp1_2m_interp = temp1_2m.interp(datetime=common_times, method="linear")
            temp2_1m_interp = temp2_1m.interp(datetime=common_times, method="linear")
            temp2_2m_interp = temp2_2m.interp(datetime=common_times, method="linear")

            # Drop NaN values
            valid_mask = ~(
                np.isnan(temp1_1m_interp.values)
                | np.isnan(temp1_2m_interp.values)
                | np.isnan(temp2_1m_interp.values)
                | np.isnan(temp2_2m_interp.values)
            )

            if not np.any(valid_mask):
                continue

            times_valid = common_times[valid_mask]
            temp1_2m_valid = temp1_2m_interp.values[valid_mask]
            temp2_2m_valid = temp2_2m_interp.values[valid_mask]

            # Apply deployment masking if available
            if use_csv_masking:
                deployed_mask = apply_deployment_masking(
                    [ds1_1m, ds1_2m, ds2_1m, ds2_2m],
                    [
                        site1_sensors["1m"],
                        site1_sensors["2m"],
                        site2_sensors["1m"],
                        site2_sensors["2m"],
                    ],
                    times_valid,
                    [temp1_2m_valid, temp1_2m_valid, temp2_2m_valid, temp2_2m_valid],
                    csv_deployment_path,
                    site1_name,
                    site2_name,
                )
            else:
                deployed_mask = np.ones(len(times_valid), dtype=bool)

            if not np.any(deployed_mask):
                continue

            # Filter to deployed periods
            temp1_2m_deployed = temp1_2m_valid[deployed_mask]
            temp2_2m_deployed = temp2_2m_valid[deployed_mask]

            # Calculate lapse rates
            if elevation1 > elevation2:
                lapse_rates = (
                    temp1_2m_deployed - temp2_2m_deployed
                ) / elevation_diff_km
            else:
                lapse_rates = (
                    temp2_2m_deployed - temp1_2m_deployed
                ) / elevation_diff_km

            result_data[resolution] = lapse_rates.tolist()

        except Exception as e:
            print(f"      Error processing resolution {resolution}: {e}")
            continue

    return result_data


