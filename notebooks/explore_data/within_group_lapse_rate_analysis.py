def load_site_elevations(csv_deployment_path):
    """Load site elevation data from deployment CSV"""
    elevations = {}
    if csv_deployment_path.exists():
        df = pd.read_csv(csv_deployment_path)
        for _, row in df.iterrows():
            site = row["site"]
            elevation = row["site_elevation"]
            if pd.notna(site) and pd.notna(elevation):
                elevations[site] = float(elevation)
    return elevations


def load_site_data(netcdf_files):
    """Load and organize NetCDF datasets by site"""
    site_data = {}

    for nc_file in tqdm(netcdf_files, desc="Loading datasets"):
        try:
            ds = xr.open_dataset(nc_file)

            site_name = ds.attrs.get("site_name", "Unknown")
            sensor_height = ds.attrs.get("sensor_height", "Unknown")
            sensor_id = ds.attrs.get("sensor_id", "Unknown")

            site_key = site_name if site_name != "Unknown" else f"Sensor_{sensor_id}"

            if site_key not in site_data:
                site_data[site_key] = {}

            if sensor_height in ["1m", "2m"]:
                # Store original CSV filename for deployment masking
                original_csv_filename = None
                if hasattr(ds, "attrs") and "original_filename" in ds.attrs:
                    original_csv_filename = ds.attrs["original_filename"]
                else:
                    original_csv_filename = nc_file.name

                site_data[site_key][sensor_height] = {
                    "dataset": ds,
                    "sensor_id": sensor_id,
                    "file": nc_file.name,
                    "original_csv_filename": original_csv_filename,
                }

        except Exception as e:
            print(f"Error loading {nc_file}: {e}")
            continue

    return site_data


def group_sites_by_prefix(sites_with_both, site_elevations):
    """Group sites by their letter prefix (A, B, D, etc.)"""

    groups = {}

    for site_name in sites_with_both.keys():
        # Extract letter prefix (e.g., 'A' from 'A01', 'TKG' from 'TKG4')
        if site_name[0].isalpha():
            # Handle cases like 'TKG4' - take all leading letters
            prefix = ""
            for char in site_name:
                if char.isalpha():
                    prefix += char
                else:
                    break
        else:
            continue  # Skip sites that don't start with letter

        if prefix not in groups:
            groups[prefix] = {"sites": [], "elevations": {}}

        groups[prefix]["sites"].append(site_name)
        groups[prefix]["elevations"][site_name] = site_elevations.get(site_name, 0)

    # Filter groups with 2+ sites and sort by elevation
    filtered_groups = {}
    for prefix, group_info in groups.items():
        if len(group_info["sites"]) >= 2:
            # Sort sites by elevation (ascending)
            sorted_sites = sorted(
                group_info["sites"], key=lambda x: group_info["elevations"][x]
            )
            group_info["sites"] = sorted_sites
            filtered_groups[prefix] = group_info

    return filtered_groups


def process_custom_sequences(sites_with_both, site_elevations):
    """Process custom site sequences defined in CUSTOM_SEQUENCES"""

    custom_groups = {}

    for i, sequence in enumerate(CUSTOM_SEQUENCES):
        # Check if all sites in sequence are available
        available_sites = [site for site in sequence if site in sites_with_both]

        if len(available_sites) >= 2:  # Need at least 2 sites for analysis
            group_name = f"Custom_{i + 1}"

            # Create group info structure
            group_info = {"sites": available_sites, "elevations": {}}

            # Add elevation info for each site
            for site in available_sites:
                group_info["elevations"][site] = site_elevations.get(site, 0)

            # Sort sites by elevation (ascending) - maintain elevation order
            sorted_sites = sorted(
                available_sites, key=lambda x: group_info["elevations"][x]
            )
            group_info["sites"] = sorted_sites

            custom_groups[group_name] = group_info

            print(f"  Added custom sequence {group_name}: {sequence}")
            if len(available_sites) < len(sequence):
                missing_sites = [
                    site for site in sequence if site not in sites_with_both
                ]
                print(f"    Note: Missing sites {missing_sites}")
        else:
            missing_sites = [site for site in sequence if site not in sites_with_both]
            print(
                f"  Skipping custom sequence {sequence} - insufficient available sites"
            )
            print(f"    Available: {available_sites}, Missing: {missing_sites}")

    return custom_groups


