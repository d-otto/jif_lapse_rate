def plot_temp_elevation_relationships(ax, site_temp_data, group_name):
    """Plot mean temperature vs elevation with regression lines and confidence intervals"""

    if not site_temp_data:
        ax.text(
            0.5,
            0.5,
            "No temperature data available",
            transform=ax.transAxes,
            ha="center",
            va="center",
        )
        ax.set_title(f"{group_name}: Temperature vs Elevation")
        return

    # Extract data for plotting
    elevations = []
    temp_all = []
    temp_day = []
    temp_night = []
    std_all = []
    std_day = []
    std_night = []
    site_names = []

    for site_name, data in site_temp_data.items():
        elevations.append(data["elevation"])
        site_names.append(site_name)

        # Use 2m sensor data for comparison
        temp_all.append(data["temp_means"]["all_times"]["2m"])
        temp_day.append(data["temp_means"]["daytime"]["2m"])
        temp_night.append(data["temp_means"]["nighttime"]["2m"])

        # Get standard deviations for each time period
        std_all.append(data["temp_stds"]["all_times"]["2m"])
        std_day.append(data["temp_stds"]["daytime"]["2m"])
        std_night.append(data["temp_stds"]["nighttime"]["2m"])

    elevations = np.array(elevations)
    temp_all = np.array(temp_all)
    temp_day = np.array(temp_day)
    temp_night = np.array(temp_night)
    std_all = np.array(std_all)
    std_day = np.array(std_day)
    std_night = np.array(std_night)

    # Remove NaN values for each time period
    valid_all = ~np.isnan(temp_all)
    valid_day = ~np.isnan(temp_day)
    valid_night = ~np.isnan(temp_night)

    colors = {"all_times": "blue", "daytime": "orange", "nighttime": "purple"}

    # Function to add regression line with regression standard error
    def add_regression_line(x_vals, y_vals, std_vals, valid_mask, color, label, marker):
        if np.sum(valid_mask) >= 2:  # Need at least 2 points for regression
            x_valid = x_vals[valid_mask]
            y_valid = y_vals[valid_mask]

            # Perform linear regression
            slope, intercept, r_value, _, _ = linregress(x_valid, y_valid)

            # Calculate lapse rate (°C/km)
            lapse_rate = slope * 1000  # Convert from °C/m to °C/km

            # Plot data points first
            ax.plot(
                x_valid, y_valid, marker, color=color, markersize=6, linestyle="None"
            )

            # Plot regression line
            y_pred = slope * x_valid + intercept
            ax.plot(
                x_valid,
                y_pred,
                "-",
                color=color,
                linewidth=2,
                label=f"{label}: {lapse_rate:.1f}°C/km (R²={r_value**2:.3f})",
            )

            # Calculate regression standard error for confidence interval
            residuals = y_valid - y_pred
            residual_std = np.std(residuals, ddof=2)  # ddof=2 for slope and intercept

            # Plot ±1 standard error confidence interval based on regression residuals
            ax.fill_between(
                x_valid,
                y_pred - residual_std,
                y_pred + residual_std,
                color=color,
                alpha=0.2,
            )

    # Add regression lines for each time period
    add_regression_line(
        elevations, temp_all, std_all, valid_all, colors["all_times"], "All times", "o"
    )
    add_regression_line(
        elevations,
        temp_day,
        std_day,
        valid_day,
        colors["daytime"],
        "Daytime (4am-8pm)",
        "s",
    )
    add_regression_line(
        elevations,
        temp_night,
        std_night,
        valid_night,
        colors["nighttime"],
        "Nighttime (8pm-4am)",
        "^",
    )

    # Add site labels
    for i, (elev, temp, site) in enumerate(zip(elevations, temp_all, site_names)):
        if not np.isnan(temp):
            ax.annotate(
                site,
                (elev, temp),
                xytext=(5, 5),
                textcoords="offset points",
                fontsize=8,
                alpha=0.7,
            )

    # Consolidate all styling at the end
    ax.set_xlabel("Elevation (m)")
    ax.set_ylabel("Mean Temperature (°C)")
    ax.set_title(f"{group_name}: Temperature vs Elevation")
    ax.legend(loc="best")
    apply_plot_styling(ax, style_type='default')


def plot_lapse_rate_histograms(ax, lapse_rate_data, site_temp_data, group_name):
    """Plot lapse rate histograms for 1H averaged data only"""

    if (
        not lapse_rate_data
        or "1H" not in lapse_rate_data
        or len(lapse_rate_data["1H"]) == 0
    ):
        ax.text(
            0.5,
            0.5,
            "No 1H lapse rate data available",
            transform=ax.transAxes,
            ha="center",
            va="center",
        )
        ax.set_title(f"{group_name}: Lapse Rate Distributions (1H averaged)")
        return

    # Only show 1H data
    resolution = "1H"
    color = "green"
    alpha_val = 0.7

    # Standardized bins: +/- 20°C/km with 0.5°C/km width
    bins = np.arange(-20.0, 21, 1)

    lapse_rates = np.array(lapse_rate_data[resolution])

    # Filter out extreme values
    lapse_rates = lapse_rates[(lapse_rates >= -50) & (lapse_rates <= 50)]

    if len(lapse_rates) > 0:
        # Plot histogram
        ax.hist(
            lapse_rates,
            bins=bins,
            alpha=alpha_val,
            color=color,
            density=True,
            edgecolor="black",
            linewidth=0.3,
        )

        # Calculate statistics
        mean_lr = np.mean(lapse_rates)
        median_lr = np.median(lapse_rates)

        # Add vertical line for mean
        ax.axvline(
            x=mean_lr,
            color=color,
            linestyle="-",
            linewidth=2,
            alpha=0.8,
        )

        # Create legend entry with mean and median
        legend_entry = f"{resolution}: μ={mean_lr:.1f}, M={median_lr:.1f}"

    # Reference lines
    ax.axvline(x=0, color="black", linestyle="-", alpha=1.0, linewidth=2)
    ax.axvline(x=-6.5, color="black", linestyle="--", alpha=0.8, linewidth=2)

    # Create legend with statistics
    if len(lapse_rates) > 0:
        ax.legend([legend_entry], loc="upper right", fontsize=8)
    else:
        ax.text(
            0.5,
            0.5,
            "No valid 1H lapse rate data",
            transform=ax.transAxes,
            ha="center",
            va="center",
        )
    
    # Consolidate all styling at the end
    ax.set_xlim(-20, 20)
    ax.set_xlabel("Lapse Rate (°C/km)")
    ax.set_ylabel("Density")
    ax.set_title(f"{group_name}: Lapse Rate Distributions (1H averaged)")
    apply_plot_styling(ax, style_type='default')


def plot_temporal_lapse_analysis(ax, group_data, site_temp_data, group_name):
    """Plot temporal lapse rates by time period using existing group data"""

    if not group_data["lapse_rates"] or not group_data["times"]:
        ax.text(
            0.5,
            0.5,
            "No lapse rate time series available",
            transform=ax.transAxes,
            ha="center",
            va="center",
        )
        ax.set_title(f"{group_name}: Temporal Lapse Rate Analysis")
        return

    # Collect all lapse rates and timestamps
    all_times = []
    all_lapse_rates = []

    for pair_times, pair_lapse_rates in zip(
        group_data["times"], group_data["lapse_rates"]
    ):
        all_times.extend(pair_times)
        all_lapse_rates.extend(pair_lapse_rates)

    if not all_times:
        ax.text(
            0.5,
            0.5,
            "No temporal data available",
            transform=ax.transAxes,
            ha="center",
            va="center",
        )
        ax.set_title(f"{group_name}: Temporal Lapse Rate Analysis")
        return

    # Create DataFrame
    df = pd.DataFrame(
        {"datetime": pd.to_datetime(all_times), "lapse_rate": all_lapse_rates}
    )
    df.set_index("datetime", inplace=True)

    # Filter by time periods and aggregate hourly lapse rates to daily means
    period_data = {}

    for period_name, (start_hour, end_hour) in TIME_PERIODS.items():
        if period_name == "nighttime" and end_hour < start_hour:
            # Handle wrap-around for nighttime (20:00 to 04:00)
            time_mask = (df.index.hour >= start_hour) | (df.index.hour < end_hour)
        else:
            # Normal time range
            time_mask = (df.index.hour >= start_hour) & (df.index.hour < end_hour)

        period_df = df[time_mask]
        if len(period_df) > 0:
            # Take daily means of the hourly lapse rate values
            daily_means = period_df.resample("1D").mean().dropna()
            if len(daily_means) > 0:
                period_data[period_name] = daily_means

    # Define colors and markers for each time period
    colors = {"all_times": "blue", "daytime": "orange", "nighttime": "purple"}
    markers = {"all_times": "o", "daytime": "s", "nighttime": "^"}
    labels = {
        "all_times": "All times",
        "daytime": "Daytime (4am-8pm)",
        "nighttime": "Nighttime (8pm-4am)",
    }

    # Plot each time period
    for period_name in ["all_times", "daytime", "nighttime"]:
        if period_name in period_data:
            daily_data = period_data[period_name]
            ax.plot(
                daily_data.index,
                daily_data["lapse_rate"],
                color=colors[period_name],
                marker=markers[period_name],
                linewidth=2,
                markersize=4,
                alpha=0.8,
                label=f"{labels[period_name]} (n={len(daily_data)})",
            )

    # Reference lines
    ax.axhline(y=0, color="black", linestyle="-", alpha=1.0, linewidth=2)
    ax.axhline(y=-6.5, color="black", linestyle="--", alpha=0.8, linewidth=2)

    ax.set_ylabel("Daily Mean Lapse Rate (°C/km)")
    ax.set_title(f"{group_name}: Temporal Lapse Rate Analysis (1H → daily aggregated)")
    ax.legend(loc="best", fontsize=8)
    ax.grid(True, alpha=0.3)
    ax.set_ylim(-20, 20)

    # Format x-axis with 7-day major locator and daily minor locator
    if period_data:
        ax.xaxis.set_major_locator(mdates.WeekdayLocator(interval=1))  # Every 7 days
        ax.xaxis.set_minor_locator(mdates.DayLocator())  # Every day
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%m/%d"))
        ax.tick_params(axis="x", rotation=45)
        ax.grid(True, which="minor", alpha=0.2)  # Daily grid lines


def plot_sensor_height_lapse_comparison(
    ax,
    sites,
    sites_with_both,
    site_elevations,
    csv_deployment_path,
    use_csv_masking,
    group_name,
):
    """Plot 2m vs 1m temperature scatter plot with site-specific colors and regression lines"""

    # Calculate mean temperature data for all sites
    site_temp_data_2m = {}
    site_temp_data_1m = {}
    site_names = []

    for site_name in sites:
        if site_name not in sites_with_both:
            continue

        try:
            # Get both sensor datasets
            ds_2m = sites_with_both[site_name]["2m"]["dataset"]
            ds_1m = sites_with_both[site_name]["1m"]["dataset"]
            
            temp_2m = ds_2m["temp_c"].dropna("datetime")
            temp_1m = ds_1m["temp_c"].dropna("datetime")

            # Convert to pandas and calculate means
            temp_2m_df = temp_2m.to_pandas()
            temp_1m_df = temp_1m.to_pandas()
            
            # Calculate mean temperatures
            mean_temp_2m = temp_2m_df.mean()
            mean_temp_1m = temp_1m_df.mean()
            
            if not (np.isnan(mean_temp_2m) or np.isnan(mean_temp_1m)):
                site_temp_data_2m[site_name] = mean_temp_2m
                site_temp_data_1m[site_name] = mean_temp_1m
                site_names.append(site_name)

        except Exception as e:
            print(f"    Error processing {site_name} for sensor height comparison: {e}")
            continue

    if len(site_temp_data_2m) < 2:
        ax.text(
            0.5,
            0.5,
            "Insufficient data for sensor height comparison",
            transform=ax.transAxes,
            ha="center",
            va="center",
        )
        ax.set_title(f"{group_name}: 2m vs 1m Temperature Comparison")
        return

    # Convert to arrays for analysis
    temps_2m = np.array([site_temp_data_2m[site] for site in site_names])
    temps_1m = np.array([site_temp_data_1m[site] for site in site_names])

    # Generate distinct colors for each site
    import matplotlib.cm as cm
    colors = cm.Set1(np.linspace(0, 1, len(site_names)))
    
    # Plot each site with distinct color and individual regression line
    for i, site_name in enumerate(site_names):
        temp_1m_site = temps_1m[i]
        temp_2m_site = temps_2m[i]
        color = colors[i]
        
        # Plot the data point for this site
        ax.scatter(
            temp_1m_site, temp_2m_site, 
            color=color, s=80, alpha=0.8, 
            label=f"{site_name} ({site_elevations[site_name]:.0f}m)",
            edgecolors='black', linewidth=0.5
        )
        
        # Add site label next to point
        ax.annotate(
            site_name,
            (temp_1m_site, temp_2m_site),
            xytext=(5, 5),
            textcoords="offset points",
            fontsize=9,
            fontweight='bold',
            color=color,
            alpha=0.9,
        )

    # Overall regression line for all sites combined
    if len(temps_1m) >= 2:
        slope, intercept, r_value, _, _ = linregress(temps_1m, temps_2m)
        
        # Create smooth line for regression
        x_range = np.linspace(temps_1m.min(), temps_1m.max(), 100)
        y_pred = slope * x_range + intercept
        
        ax.plot(
            x_range, y_pred, 
            '--', color='black', linewidth=2, alpha=0.7,
            label=f'Overall Fit: R²={r_value**2:.3f}'
        )
        
        # Add 1:1 reference line (where 2m = 1m temperatures)
        temp_min = min(temps_1m.min(), temps_2m.min())
        temp_max = max(temps_1m.max(), temps_2m.max())
        ax.plot(
            [temp_min, temp_max], [temp_min, temp_max], 
            ':', color='gray', linewidth=1.5, alpha=0.6,
            label='1:1 Reference'
        )

    # Set labels and title
    ax.set_xlabel("1m Sensor Temperature (°C)", fontsize=11)
    ax.set_ylabel("2m Sensor Temperature (°C)", fontsize=11)
    ax.set_title(f"{group_name}: 2m vs 1m Sensor Temperature Comparison", fontsize=12, fontweight='bold')
    
    # Customize legend for better visual clarity
    legend = ax.legend(loc='upper left', bbox_to_anchor=(0.02, 0.98), frameon=True, 
                      fancybox=True, shadow=True, fontsize=8)
    legend.get_frame().set_facecolor('white')
    legend.get_frame().set_alpha(0.9)
    
    # Add grid for better readability
    ax.grid(True, alpha=0.3, linestyle='-', linewidth=0.5)
    
    # Equal aspect ratio and tight layout
    ax.set_aspect('equal', adjustable='box')
    
    # Add text box with temperature difference statistics
    temp_diff = temps_2m - temps_1m
    mean_diff = np.mean(temp_diff)
    std_diff = np.std(temp_diff)
    
    textstr = f'2m - 1m Difference:\nMean: {mean_diff:.3f}°C\nStd: {std_diff:.3f}°C'
    props = dict(boxstyle='round', facecolor='lightblue', alpha=0.7)
    ax.text(0.98, 0.02, textstr, transform=ax.transAxes, fontsize=8,
            verticalalignment='bottom', horizontalalignment='right', bbox=props)


