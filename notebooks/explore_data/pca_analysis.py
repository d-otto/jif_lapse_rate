def save_pca_results(pca_results, sensor_info, time_index, output_dir):
    """Save PCA results to CSV files"""
    
    print("\nSaving PCA results...")
    
    # Save explained variance
    variance_df = pd.DataFrame({
        'PC': [f'PC{i+1}' for i in range(len(pca_results['explained_variance_ratio']))],
        'Explained_Variance_Ratio': pca_results['explained_variance_ratio'],
        'Cumulative_Variance': pca_results['cumulative_variance']
    })
    variance_df.to_csv(output_dir / "pca_explained_variance.csv", index=False)
    
    # Save loadings with sensor information
    loadings_df = sensor_info.copy()
    for i in range(pca_results['loadings'].shape[1]):
        loadings_df[f'PC{i+1}_loading'] = pca_results['loadings'][:, i]
    loadings_df.to_csv(output_dir / "pca_loadings.csv", index=False)
    
    # Save principal component scores (would include time in real implementation)
    pc_scores_df = pd.DataFrame(pca_results['principal_components'])
    pc_scores_df.columns = [f'PC{i+1}' for i in range(pc_scores_df.shape[1])]
    pc_scores_df['time_index'] = range(len(pc_scores_df))  # Placeholder for time
    pc_scores_df.to_csv(output_dir / "pca_scores.csv", index=False)
    
    # Save summary statistics
    summary = {
        'total_sensors': len(sensor_info),
        'total_components': len(pca_results['explained_variance_ratio']),
        'pc1_variance': pca_results['explained_variance_ratio'][0],
        'pc2_variance': pca_results['explained_variance_ratio'][1],
        'pc1_pc2_cumulative': pca_results['cumulative_variance'][1],
        'components_95_percent': pca_results['n_95_percent']
    }
    
    summary_df = pd.DataFrame([summary])
    summary_df.to_csv(output_dir / "pca_summary.csv", index=False)
    
    print("PCA results saved:")
    print("  - Explained variance: pca_explained_variance.csv")
    print("  - Loadings: pca_loadings.csv") 
    print("  - Scores: pca_scores.csv")
    print("  - Summary: pca_summary.csv")


